import { useEffect, useState } from 'react';
import { AnimatePresence } from 'framer-motion';
import { RefreshCw, ShieldAlert } from 'lucide-react';
import { api } from '../api';
import { sfx } from '../sound';
import { Info, WeeklyBanner } from '../components/Info';
import { useModal } from '../components/Modal';
import MapCleaner from '../components/MapCleaner';
import PAGES from '../data/pages.json';
import type { MaintState } from '../types';

const M = PAGES.maintenance;
const CLEAN = [
  { key: 'temp', title: 'Purge Windows temp files (%TEMP% & Windows\\Temp)', desc: 'Deletes temporary cache files generated by Windows and desktop programs.' },
  { key: 'win_update', title: 'Purge Windows Update cache (SoftwareDistribution)', desc: 'Clears residual Windows update download installers to recover drive storage.' },
  { key: 'discord_steam', title: 'Purge Discord & Steam web cache (never logs you out)', desc: 'Removes bloated CEF/Chromium web cache without clearing login sessions.' },
  { key: 'thumb', title: 'Purge Explorer thumbnail cache (thumbcache_*.db)', desc: 'Rebuilds the Windows file explorer thumbnail database to fix icon corruption.' },
  { key: 'recycle', title: 'Empty the Windows Recycle Bin (purges deleted trash)', desc: 'Permanently frees space taken by discarded files in your Recycle Bin.' },
  { key: 'dns', title: 'Flush Windows DNS cache (refreshes server lookups)', desc: 'Flushes the local DNS resolver cache to fix community server connection timeouts.' },
] as const;
const TOOLS = [
  { key: 'cleanmgr', label: 'Launch Disk Cleanup', admin: false, tip: M.cleanmgr },
  { key: 'trim', label: 'Run SSD TRIM (defrag /O)', admin: true, tip: M.trim },
  { key: 'startup', label: 'Startup apps manager', admin: false, tip: M.startup },
  { key: 'sfc', label: 'System File Checker (SFC)', admin: true, tip: M.sfc },
  { key: 'dism', label: 'DISM health restore', admin: true, tip: M.dism },
  { key: 'winsxs', label: 'DISM WinSxS cleanup', admin: true, tip: M.winsxs },
] as const;

export default function Maintenance({ busy, setBusy, go }: { busy: boolean; setBusy: (b: boolean) => void; go: (id: 'engine' | 'maintenance') => void }) {
  const [st, setSt] = useState<MaintState | null>(null);
  const [daysOpt, setDaysOpt] = useState<number | null>(null);
  const [mapStat, setMapStat] = useState('Scanning maps & workshop content...');
  const [sel, setSel] = useState<Record<string, boolean>>({ temp: true, win_update: true, discord_steam: true, thumb: true, recycle: false, dns: true });
  const openModal = useModal();
  const [cleaner, setCleaner] = useState(false);
  const load = () => { void api.maintState().then(setSt); };
  useEffect(() => {
    load();
    void api.dashboard().then((d) => setDaysOpt(d.days_opt));
    void api.mapStats().then((m) => setMapStat(`${m.count} custom maps detected (${m.gb} GB storage)`));
  }, []);

  const run = () => {
    const chosen = CLEAN.filter((c) => sel[c.key]);
    if (!chosen.length) { openModal({ kind: 'warn', label: 'Nothing selected', title: 'Pick at least one clean-up' }); return; }
    openModal({
      kind: 'q', label: 'Confirm', title: 'Run the selected clean-up?',
      body: `This will:\n${chosen.map((c) => `- ${c.title}`).join('\n')}\n\nDeleted files cannot be restored.`,
      confirm: { text: 'Run clean-up', run: async () => { setBusy(true); const r = await api.maintRun(sel); if (!r.ok) { setBusy(false); openModal({ kind: 'warn', label: 'Problem', title: 'Not started', body: r.error }); } } },
    });
  };
  const tool = async (key: string, label: string, admin: boolean) => {
    if (admin && st && !st.admin) { openModal({ kind: 'warn', label: 'Administrator needed', title: label, body: 'This repair tool needs Administrator. Use Relaunch as Administrator above.' }); return; }
    sfx.click();
    const r = await api.maintTool(key);
    if (!r.ok) openModal({ kind: 'warn', label: 'Problem', title: label, body: r.error });
  };
  const verify = async () => {
    sfx.click(); setMapStat('Scanning & verifying Workshop VPK headers...');
    const r = await api.vpkVerify();
    setMapStat(r.message);
    openModal({ kind: r.corrupted ? 'warn' : 'ok', label: 'Workshop VPK health', title: r.corrupted ? `${r.corrupted} damaged VPK packs found` : 'All Workshop VPK packs are healthy',
      body: `${r.message}${r.bad.length ? `\n\nDamaged: ${r.bad.join(', ')}\n\nUse Repair corrupted VPKs to let Steam download them again.` : ''}` });
  };
  const repair = () => openModal({
    kind: 'q', label: 'Confirm', title: 'Repair corrupted VPKs?', body: 'Removes only damaged or incomplete Workshop folders so Steam downloads them again cleanly. Healthy maps are not touched.',
    confirm: { text: 'Repair', run: async () => { const r = await api.vpkRepair(); openModal({ kind: 'ok', label: 'Workshop VPK repair', title: r.count ? 'Repair complete' : 'Nothing to repair', body: r.message }); } },
  });

  return (
    <section className="view on">
      <div className="vhead"><div><div className="decal">// 08 · housekeeping</div><h1>Safe system &amp; storage maintenance</h1><p>PC clean-up: free up storage, clear cache bloat, inspect drive health and flush DNS.</p></div>
        <button className="btn cut ghost sm" onClick={() => { sfx.click(); load(); }}><RefreshCw size={13} /> Refresh</button></div>

      <WeeklyBanner daysOpt={daysOpt} daysMaint={st?.days_maint} go={go} />
      <Info title={M.purpose_title} text={M.purpose} open={false} tone="var(--cyan)" />

      {st && !st.admin && (
        <div className="glass card" style={{ display: 'flex', gap: 14, alignItems: 'center', flexWrap: 'wrap' }}>
          <ShieldAlert size={20} color="var(--cyan)" />
          <div style={{ flex: 1, minWidth: 220 }}><div className="t">{M.standard.replace(/^[^A-Za-z]*/, '')}</div><div className="d" style={{ color: 'var(--tx2)' }}>{M.standard_desc}</div></div>
          <button className="btn cut ghost sm" title={M.relaunch_tip} onClick={() => { sfx.click(); void api.relaunchAdmin(); }}>Relaunch as Administrator</button>
        </div>
      )}

      <div className="glass card">
        <div className="sect" style={{ marginBottom: 8 }}>Storage capacity &amp; health monitor</div>
        {st?.drives.map((d) => {
          const free = (d.free_gb / d.total_gb) * 100, tone = d.is_critical ? 'var(--bad)' : free < 25 ? 'var(--amber)' : 'var(--ok)';
          return (
            <div className="row" key={d.drive}>
              <div className="mono" style={{ width: 36, fontWeight: 700 }}>{d.drive}</div>
              <div className="grow"><div className="bar" style={{ margin: 0 }}><i style={{ width: `${d.used_pct}%`, background: tone }} /></div></div>
              <div className="mono" style={{ fontSize: 12, color: tone, minWidth: 190, textAlign: 'right' }}>{d.free_gb.toFixed(1)} GB free of {d.total_gb.toFixed(0)} GB</div>
            </div>
          );
        })}
        {st?.drives.some((d) => d.is_critical) && <div className="decal" style={{ color: 'var(--bad)', marginTop: 8, textTransform: 'none', letterSpacing: 0 }}>Notice: when drives exceed 85% full, SSD write cache performance degrades and causes in-game micro-stuttering.</div>}
      </div>

      <div className="glass card">
        <div className="sect">{M.map_title}</div>
        <div className="d" style={{ color: 'var(--tx2)', margin: '4px 0 10px' }}>{M.map_desc}</div>
        <div style={{ display: 'flex', gap: 8, flexWrap: 'wrap' }}>
          <button className="btn cut ghost" title={M.map_tip} onClick={() => { sfx.click(); setCleaner(true); }}>Inspect &amp; clean custom maps</button>
          <button className="btn cut ghost" title={M.vpk_tip} onClick={() => void verify()}>Verify Workshop VPK health</button>
          <button className="btn cut ghost" title={M.repair_tip} onClick={() => { sfx.click(); repair(); }}>Repair corrupted VPKs</button>
        </div>
        <div className="mono" style={{ fontSize: 12, color: 'var(--cyan)', marginTop: 10 }}>{mapStat}</div>
      </div>

      <div className="glass card">
        <div className="sect" style={{ marginBottom: 4 }}>Safe disk &amp; cache clean-up</div>
        {CLEAN.map((c) => (
          <div className="row" key={c.key}>
            <div className="grow"><div className="t">{c.title}</div><div className="d">{c.desc}</div></div>
            <button className="sw" role="switch" aria-checked={sel[c.key]} aria-label={c.title} onClick={() => { sfx.toggle(); setSel({ ...sel, [c.key]: !sel[c.key] }); }} />
          </div>
        ))}
        <div style={{ display: 'flex', justifyContent: 'flex-end', marginTop: 10 }}>
          <button className="btn cut amber pri" disabled={busy} title={M.cleanup_tip} onClick={run}>{busy ? 'Working…' : 'Run selected PC clean-up'}</button>
        </div>
      </div>

      <div className="glass card">
        <div className="sect" style={{ marginBottom: 10 }}>{M.tools_title}</div>
        <div style={{ display: 'flex', gap: 8, flexWrap: 'wrap' }}>
          {TOOLS.map((t) => <button key={t.key} className="btn cut ghost sm" title={t.tip} onClick={() => void tool(t.key, t.label, t.admin)}>{t.label}{t.admin ? ' · admin' : ''}</button>)}
        </div>
      </div>
      <AnimatePresence>{cleaner && <MapCleaner onClose={() => setCleaner(false)} />}</AnimatePresence>
    </section>
  );
}
