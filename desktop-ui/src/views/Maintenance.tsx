import { useEffect, useState } from 'react';
import { AnimatePresence } from 'framer-motion';
import { RefreshCw, ShieldAlert } from 'lucide-react';
import { api, on } from '../api';
import { sfx } from '../sound';
import { Info, WeeklyBanner } from '../components/Info';
import { useAdminPrompt, useModal } from '../components/Modal';
import MapCleaner from '../components/MapCleaner';
import { StatusBar, StatusLine, useLiveStatus } from '../components/StateCheck';
import PAGES from '../data/pages.json';
import { LONG_TOOLS, RECORD_HINT, STATUS_LABEL, TOOL_INFO, TYPICAL_S, VPK_HOW, VPK_REPAIR_HOW, progressOf } from '../toolText';
import type { MaintState, ToolRun } from '../types';

const M = PAGES.maintenance;
// Microsoft's support article for SFC (it gives the same order: DISM /RestoreHealth first, then sfc /scannow)
const MS_SFC_URL = 'https://support.microsoft.com/en-us/windows/experience/backup-recovery/using-system-file-checker-in-windows';
const clock = (s: number) => { const t = Math.max(0, Math.floor(s)); return t >= 60 ? `${Math.floor(t / 60)} min ${String(t % 60).padStart(2, '0')} s` : `${t} s`; };
const CLEAN = [
  { key: 'temp', title: 'Purge Windows temp files (%TEMP% & Windows\\Temp)', desc: 'Deletes temporary cache files generated by Windows and desktop programs.' },
  { key: 'win_update', title: 'Purge Windows Update cache (SoftwareDistribution)', desc: 'Clears residual Windows update download installers to recover drive storage.' },
  { key: 'discord_steam', title: 'Purge Discord & Steam web cache (never logs you out)', desc: 'Removes bloated CEF/Chromium web cache without clearing login sessions.' },
  { key: 'thumb', title: 'Purge Explorer thumbnail cache (thumbcache_*.db)', desc: 'Rebuilds the Windows file explorer thumbnail database to fix icon corruption.' },
  { key: 'recycle', title: 'Empty the Windows Recycle Bin (purges deleted trash)', desc: 'Permanently frees space taken by discarded files in your Recycle Bin.' },
  { key: 'dns', title: 'Flush Windows DNS cache (refreshes server lookups)', desc: 'Flushes the local DNS resolver cache to fix community server connection timeouts.' },
] as const;
// Repair tools first, in the order Microsoft recommends (DISM repairs SFC's source, then SFC, then the optional clean-up), then the others.
const TOOLS = [
  { key: 'dism', label: '1 · DISM health restore', admin: true, tip: M.dism },
  { key: 'sfc', label: '2 · System File Checker (SFC)', admin: true, tip: M.sfc },
  { key: 'winsxs', label: '3 · DISM WinSxS cleanup', admin: true, tip: M.winsxs },
  { key: 'trim', label: 'Run SSD TRIM (defrag /O)', admin: true, tip: M.trim },
  { key: 'cleanmgr', label: 'Launch Disk Cleanup', admin: false, tip: M.cleanmgr },
  { key: 'startup', label: 'Startup apps manager', admin: false, tip: M.startup },
] as const;

export default function Maintenance({ busy, setBusy, go }: { busy: boolean; setBusy: (b: boolean) => void; go: (id: 'engine' | 'maintenance') => void }) {
  const [st, setSt] = useState<MaintState | null>(null);
  const live = useLiveStatus('maintenance');
  const [daysOpt, setDaysOpt] = useState<number | null>(null);
  const [mapStat, setMapStat] = useState('Scanning maps & workshop content...');
  const [sel, setSel] = useState<Record<string, boolean>>({ temp: true, win_update: true, discord_steam: true, thumb: true, recycle: false, dns: true });
  const openModal = useModal();
  const adminPrompt = useAdminPrompt();
  const [cleaner, setCleaner] = useState(false);
  const [running, setRunning] = useState<ToolRun | null>(null);
  const [now, setNow] = useState(Date.now() / 1000);
  const load = () => { void api.maintState().then((s) => { setSt(s); setRunning(s.tool_run); }); };
  useEffect(() => {
    const o1 = on<ToolRun>('tool_progress', (p) => { setRunning(p); setNow(Date.now() / 1000); });
    const o2 = on('tool_result', () => { setRunning(null); load(); });
    const o3 = on('job', () => { setRunning(null); load(); });
    return () => { o1(); o2(); o3(); };
  }, []);
  useEffect(() => {
    if (!running) return;
    const t = setInterval(() => setNow(Date.now() / 1000), 1000);
    return () => clearInterval(t);
  }, [running]);
  useEffect(() => {
    load();
    void api.dashboard().then((d) => setDaysOpt(d.days_opt));
    void api.mapStats().then((m) => setMapStat(`${m.count} custom maps detected (${m.gb} GB storage)`));
  }, []);

  const run = () => {
    const chosen = CLEAN.filter((c) => sel[c.key]);
    if (!chosen.length) { openModal({ kind: 'warn', label: 'Nothing selected', title: 'Pick at least one clean-up' }); return; }
    openModal({
      kind: 'q', label: 'Confirm', title: 'Run the selected clean-up?',
      body: `This will:\n${chosen.map((c) => `- ${c.title}`).join('\n')}\n\nDeleted files cannot be restored.`,
      confirm: { text: 'Run clean-up', run: async () => { setBusy(true); const r = await api.maintRun(sel); if (!r.ok) { setBusy(false); openModal({ kind: 'warn', label: 'Problem', title: 'Not started', body: r.error }); } } },
    });
  };
  const start = async (key: string, label: string) => {
    const r = await api.maintTool(key);
    if (!r.ok) { openModal({ kind: 'warn', label: 'Problem', title: label, body: r.error }); return; }
    if (LONG_TOOLS.includes(key)) { setRunning({ name: key, started: r.started ?? Date.now() / 1000, pct: null }); setNow(Date.now() / 1000); }
  };
  const tool = async (key: string, label: string, admin: boolean) => {
    if (admin && st && !st.admin) { adminPrompt(label, 'maintenance'); return; }
    sfx.click();
    const info = TOOL_INFO[key];
    if (!info) { await start(key, label); return; }
    openModal({
      kind: 'q', label: 'Start Windows tool', title: `Start ${info.name}?`,
      body: `This ${info.what}.\n\nIt usually takes ${info.time}, and the percentage can stay still for a long time. That is normal.\n\nYou can keep using the app and your PC. Please do not shut down or put the PC to sleep, and keep this app open until it tells you it is finished.\n\nWhen it ends, a window here tells you the result and how the app knows.`,
      confirm: { text: 'Start', run: () => start(key, label) },
    });
  };
  const verify = async () => {
    sfx.click(); setMapStat('Scanning & verifying Workshop VPK headers...');
    const r = await api.vpkVerify();
    setMapStat(r.message);
    openModal({ kind: r.corrupted ? 'warn' : 'ok', label: 'Workshop VPK health', title: r.corrupted ? `${r.corrupted} damaged VPK packs found` : 'All Workshop VPK packs are healthy',
      body: `${r.message}${r.bad.length ? `\n\nDamaged:\n${r.bad.map((b) => `• ${b}`).join('\n')}\n\nUse Repair corrupted VPKs to let Steam download them again.` : ''}\n\n${VPK_HOW}` });
  };
  const openTool = async (name: string, what: 'report' | 'record' | 'folder') => {
    sfx.click();
    const r = await api.maintToolOpen(name, what);
    if (!r.ok) openModal({ kind: 'warn', label: TOOL_INFO[name]?.name ?? 'Windows tool', title: what === 'report' ? 'No report to open' : 'Could not open it', body: r.error });
  };
  const runProgress = running ? progressOf(running.pct, now - running.started, (st?.tool_last?.[running.name]?.seconds ?? 0) > 20 ? st!.tool_last[running.name].seconds : TYPICAL_S[running.name] ?? 600) : null;
  const repair = () => openModal({
    kind: 'q', label: 'Confirm', title: 'Repair corrupted VPKs?', body: `Removes only damaged or incomplete Workshop folders so Steam downloads them again cleanly. Healthy maps are not touched.\n\n${VPK_REPAIR_HOW}`,
    confirm: { text: 'Repair', run: async () => { const r = await api.vpkRepair(); openModal({ kind: r.count ? 'ok' : (r.skipped ? 'warn' : 'ok'), label: 'Workshop VPK repair', title: r.count ? 'Repair complete' : (r.skipped ? 'Nothing was removed' : 'Nothing to repair'), body: r.message }); } },
  });

  return (
    <section className="view on">
      <div className="vhead"><div><div className="decal">// 08 · housekeeping</div><h1>Safe system &amp; storage maintenance</h1><p>PC clean-up: free up storage, clear cache bloat, inspect drive health and flush DNS.</p></div>
        <button className="btn cut ghost sm" onClick={() => { sfx.click(); load(); }}><RefreshCw size={13} /> Refresh</button></div>

      <WeeklyBanner daysOpt={daysOpt} daysMaint={st?.days_maint} go={go} actions={st?.days_maint == null || st.days_maint > 7 ? [{ label: 'Run Maintenance Below', run }] : []} />
      <Info title={M.purpose_title} text={M.purpose} open={false} tone="var(--cyan)" />

      {st && !st.admin && (
        <div className="glass card" style={{ display: 'flex', gap: 14, alignItems: 'center', flexWrap: 'wrap' }}>
          <ShieldAlert size={20} color="var(--cyan)" />
          <div style={{ flex: 1, minWidth: 220 }}><div className="t">{M.standard.replace(/^[^A-Za-z]*/, '')}</div><div className="d" style={{ color: 'var(--tx2)' }}>{M.standard_desc}</div></div>
          <button className="btn cut ghost sm" title={M.relaunch_tip} onClick={() => { sfx.click(); adminPrompt('Relaunch as Administrator', 'maintenance'); }}>Relaunch as Administrator</button>
        </div>
      )}

      <div className="glass card">
        <div className="sect" style={{ marginBottom: 8 }}>Storage capacity &amp; health monitor</div>
        {st?.drives.map((d) => {
          const free = (d.free_gb / d.total_gb) * 100, tone = d.is_critical ? 'var(--bad)' : free < 25 ? 'var(--amber)' : 'var(--ok)';
          return (
            <div className="row" key={d.drive}>
              <div className="mono" style={{ width: 36, fontWeight: 700 }}>{d.drive}</div>
              <div className="grow"><div className="bar" style={{ margin: 0 }}><i style={{ width: `${d.used_pct}%`, background: tone }} /></div></div>
              <div className="mono" style={{ fontSize: 12, color: tone, minWidth: 190, textAlign: 'right' }}>{d.free_gb.toFixed(1)} GB free of {d.total_gb.toFixed(0)} GB</div>
            </div>
          );
        })}
        {st?.drives.some((d) => d.is_critical) && <div className="decal" style={{ color: 'var(--bad)', marginTop: 8, textTransform: 'none', letterSpacing: 0 }}>Notice: when drives exceed 85% full, SSD write cache performance degrades and causes in-game micro-stuttering.</div>}
      </div>

      <div className="glass card">
        <div className="sect">{M.map_title}</div>
        <div className="d" style={{ color: 'var(--tx2)', margin: '4px 0 10px' }}>{M.map_desc}</div>
        <div style={{ display: 'flex', gap: 8, flexWrap: 'wrap' }}>
          <button className="btn cut ghost" title={M.map_tip} onClick={() => { sfx.click(); setCleaner(true); }}>Inspect &amp; clean custom maps</button>
          <button className="btn cut ghost" title={M.vpk_tip} onClick={() => void verify()}>Verify Workshop VPK health</button>
          <button className="btn cut ghost" title={M.repair_tip} onClick={() => { sfx.click(); repair(); }}>Repair corrupted VPKs</button>
        </div>
        <div className="mono" style={{ fontSize: 12, color: 'var(--cyan)', marginTop: 10 }}>{mapStat}</div>
      </div>

      <div className="glass card">
        <div className="sect" style={{ marginBottom: 4 }}>Safe disk &amp; cache clean-up</div>
        <StatusBar at={live.at} busy={live.busy} error={live.error} onRefresh={() => void live.refresh()} note="Under each clean-up: what is there right now and what it would remove (read-only)." />
        {CLEAN.map((c) => (
          <div className="row" key={c.key}>
            <div className="grow"><div className="t">{c.title}</div><div className="d">{c.desc}</div><StatusLine row={live.rows[c.key]} /></div>
            <button className="sw" role="switch" aria-checked={sel[c.key]} aria-label={c.title} onClick={() => { sfx.toggle(); setSel({ ...sel, [c.key]: !sel[c.key] }); }} />
          </div>
        ))}
        <div style={{ display: 'flex', justifyContent: 'flex-end', marginTop: 10 }}>
          <button className="btn cut amber pri" disabled={busy} title={M.cleanup_tip} onClick={run}>{busy ? 'Working…' : 'Run selected PC clean-up'}</button>
        </div>
      </div>

      <div className="glass card">
        <div className="sect" style={{ marginBottom: 10 }}>{M.tools_title}</div>
        <details className="guide" style={{ marginBottom: 12 }}>
          <summary className="t" style={{ cursor: 'pointer' }}>How to use SFC and DISM the right way (read this first)</summary>
          <div className="d" style={{ color: 'var(--tx2)', lineHeight: 1.6, marginTop: 6 }}>
            <p style={{ margin: '0 0 6px' }}><b>Only when something is wrong</b> (crashes or blue screens, Windows features or updates failing, errors about missing or damaged system files). They are repair tools, not weekly maintenance, and on a healthy PC they simply find nothing.</p>
            <p style={{ margin: '0 0 4px' }}><b>Before you start:</b> close CS2 and other games, plug a laptop in, keep the PC awake, and stay online (DISM downloads good files from Windows Update if it finds damage). Do not shut down while a tool runs.</p>
            <p style={{ margin: '0 0 4px' }}><b>Microsoft&apos;s recommended order:</b> DISM first, then SFC. A restart is only needed when Windows asks for one, and this app tells you when it does.</p>
            <ol style={{ margin: '4px 0 6px 18px', padding: 0 }}>
              <li><b>DISM health restore</b>. SFC repairs files from a local copy (the component store); if that copy is damaged, SFC cannot fix anything. DISM checks and repairs that copy.</li>
              <li><b>System File Checker (SFC)</b>, right after DISM finishes. It checks every protected system file and replaces damaged ones from the now healthy copy.</li>
              <li><b>Restart</b> if SFC repaired files, so Windows starts using the fixed copies. If SFC found no problems, no restart is needed.</li>
              <li>Optional: <b>DISM WinSxS clean-up</b>, only after the repairs. It frees space by removing older, superseded copies of updates (those older versions can then no longer be restored). Skip it if you are short on time.</li>
            </ol>
            <p style={{ margin: '0 0 4px' }}><b>What can happen, and what to do:</b></p>
            <ul style={{ margin: '0 0 6px 18px', padding: 0 }}>
              <li><b>DISM: completed, no restart asked</b> &rarr; run SFC straight away.</li>
              <li><b>DISM: completed, &quot;Restart the PC to finish the changes&quot;</b> &rarr; restart first, then run SFC.</li>
              <li><b>SFC: &quot;Restart needed first&quot;</b> (Windows has a repair or update waiting) &rarr; restart, then run SFC again.</li>
              <li><b>SFC: no problems found</b> &rarr; done, nothing else to do.</li>
              <li><b>SFC: problems found and repaired</b> &rarr; restart once. Running SFC again afterwards is a good extra check.</li>
              <li><b>SFC: problems found, not all fixed</b> &rarr; run DISM, restart, run SFC again. If it still cannot fix them, use Windows&apos; own repair: Settings &gt; System &gt; Recovery &gt; Fix problems using Windows Update.</li>
              <li><b>DISM: could not download the repair files</b> &rarr; check the internet connection, install pending Windows updates, restart and try again.</li>
            </ul>
            <p style={{ margin: '0 0 4px' }}>Every result shows here in plain words, with Windows&apos; own message and what to do next; the line under the buttons turns amber or red when something needs attention.</p>
            <p style={{ margin: '0 0 4px' }}>
              <b>Microsoft&apos;s own instructions:</b>{' '}
              <button className="lnk" title="Opens support.microsoft.com in your browser" onClick={() => { sfx.click(); void api.openUrl(MS_SFC_URL); }}>Using System File Checker in Windows (support.microsoft.com)</button>
            </p>
            <p style={{ margin: 0 }}><b>SSD TRIM</b> is separate and safe any time: Windows normally does it weekly by itself.</p>
          </div>
        </details>
        {running && TOOL_INFO[running.name] && (
          <div role="status" aria-live="polite" style={{ border: '1px solid var(--cyan)', borderRadius: 10, padding: '10px 14px', marginBottom: 12, background: 'var(--cyan-dim)' }}>
            <div style={{ display: 'flex', justifyContent: 'space-between', gap: 12, flexWrap: 'wrap' }}>
              <div className="t">Running: {TOOL_INFO[running.name].name}</div>
              <div className="mono" style={{ fontSize: 12, color: 'var(--cyan)' }} title={runProgress?.real ? 'The percentage Windows itself reports.' : 'Windows has not reported a percentage yet, so this is an estimate from how long the tool usually takes (on this PC, if it ran before). It never reaches 100% on its own.'}>
                {runProgress ? `${runProgress.real ? '' : 'about '}${runProgress.value.toFixed(runProgress.real && runProgress.value % 1 ? 1 : 0)}% · ${runProgress.real ? 'reported by Windows' : 'estimate'} · ` : ''}elapsed {clock(now - running.started)}
              </div>
            </div>
            <div className="bar"><i style={{ width: `${runProgress?.value ?? 0}%`, transition: 'width 1s linear', opacity: runProgress?.real ? 1 : 0.75 }} /></div>
            <div className="d" style={{ color: 'var(--tx2)', marginTop: 8 }}>
              Windows is working. {runProgress?.real ? 'This is the percentage Windows reports; it can stay still for several minutes. ' : 'Windows has not reported a percentage yet, so the bar shows an estimate from how long this usually takes. It only fills up when the tool really ends. '}
              Usually {TOOL_INFO[running.name].time}. You can use the app and the PC; do not shut down or sleep it, and keep this app open. A result window opens when it ends.
            </div>
          </div>
        )}
        <div style={{ display: 'flex', gap: 8, flexWrap: 'wrap' }}>
          {TOOLS.map((t) => {
            const locked = !!running && LONG_TOOLS.includes(t.key);
            return <button key={t.key} className="btn cut ghost sm" disabled={locked} title={locked ? 'Another Windows tool is running. Wait for its result first.' : t.tip} onClick={() => void tool(t.key, t.label, t.admin)}>{t.label}{t.admin ? ' · admin' : ''}</button>;
          })}
        </div>
        <div style={{ marginTop: 12 }}>
          {LONG_TOOLS.map((k) => {
            const l = st?.tool_last?.[k];
            const tone = !l ? 'var(--tx3)' : l.status === 'unverified' ? 'var(--amber)' : l.ok ? 'var(--ok)' : 'var(--bad)';
            return (
              <div className="d" key={k} style={{ display: 'flex', gap: 8, flexWrap: 'wrap', padding: '2px 0' }}>
                <span style={{ minWidth: 190 }}>{TOOL_INFO[k].name}</span>
                <span style={{ color: tone }}>{l ? `${STATUS_LABEL[l.status] ?? l.headline} · ${new Date(l.at).toLocaleString([], { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' })} · took ${clock(l.seconds)}` : 'not run yet on this PC'}</span>
                {l?.report && <button className="lnk" title="Opens a text copy of this result that you can keep, print or share" onClick={() => void openTool(k, 'report')}>Report</button>}
                <button className="lnk" title={`Opens what Windows itself recorded: ${RECORD_HINT[k]}`} onClick={() => void openTool(k, 'record')}>Windows&apos; record</button>
              </div>
            );
          })}
          <div className="decal" style={{ marginTop: 8, textTransform: 'none', letterSpacing: 0, lineHeight: 1.5 }}>
            Want it on paper? Every finished run is saved as a text file (<button className="lnk" onClick={() => void openTool('sfc', 'folder')}>{String.raw`Documents\CS2 Command Center\Reports`}</button>) that you can open, print or share; <b>Report</b> opens the last one. <b>Windows&apos; record</b> opens what Windows itself wrote, without this app: SFC&apos;s [SR] lines from CBS.log, DISM&apos;s dism.log, and for TRIM the Optimize Drives window (Last run column).
          </div>
        </div>
      </div>
      <AnimatePresence>{cleaner && <MapCleaner onClose={() => setCleaner(false)} />}</AnimatePresence>
    </section>
  );
}
