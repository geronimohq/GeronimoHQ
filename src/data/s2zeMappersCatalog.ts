/**
 * Searches the 500+ S2ZE mapper catalog by map name, including prefix/suffix stripping.
 */
export function lookupS2zeMapper(rawMapName: string): string | null {
  if (!rawMapName) return null;
  const clean = rawMapName.trim().toLowerCase();
  
  // 1. Direct match
  if (S2ZE_MAPPERS_CATALOG[clean]) {
    return S2ZE_MAPPERS_CATALOG[clean];
  }
  
  // 2. Stripped match (_p, _v1, _rc, etc.)
  const stripped = clean.replace(/_(?:p|v\d+[\w]*|[a-z]\d+[\w]*|rc\d+|beta\d*|final|test)$/i, '');
  if (S2ZE_MAPPERS_CATALOG[stripped]) {
    return S2ZE_MAPPERS_CATALOG[stripped];
  }
  
  // 3. Substring match
  for (const [key, mapper] of Object.entries(S2ZE_MAPPERS_CATALOG)) {
    if (clean.includes(key) || key.includes(clean) || stripped.includes(key) || key.includes(stripped)) {
      return mapper;
    }
  }
  
  return null;
}
